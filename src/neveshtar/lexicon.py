_PERSON_COL = ["م", "ی", None, "یم", "ین", "ن"]       # None: 3sg (stem-specific)
_PERSON_FRM = ["م", "ی", "د", "یم", "ید", "ند"]


@dataclass(frozen=True)
class Rule:
    surface: str            # normalised spoken form (what is matched)
    written: str            # first alternative (what --mode applies)
    alts: Tuple[str, ...]   # all alternatives incl. the first
    conf: str
    cat: str
    note: str = ""


def _parse_table() -> List[Rule]:
    rules: List[Rule] = []
    for raw in _TABLE.strip().splitlines():
        raw = raw.strip()
        if not raw or raw.startswith("#"):
            continue
        parts = [p.strip() for p in raw.split(";", 3)]
        lhs, conf, cat = parts[0], parts[1], parts[2]
        note = parts[3] if len(parts) > 3 else ""
        spoken, written = [x.strip() for x in lhs.split("=")]
        alts = tuple(a.strip() for a in written.split("/"))
        for s in spoken.split("|"):
            rules.append(Rule(s.strip(), alts[0], alts, conf, cat, note))
    return rules


def _verb_rules() -> List[Rule]:
    out: List[Rule] = []
    seen = set()

    def add(spoken: str, written: str, conf: str = "high"):
        if spoken == written:
            return
        for neg in ("", "ن"):
            forms = {f"{neg}می{ZW}{spoken}": f"{neg}می{ZW}{written}", f"{neg}می{spoken}": f"{neg}می{ZW}{written}",
                     f"{neg}می {spoken}": f"{neg}می{ZW}{written}"}
            for k, v in forms.items():
                if k not in seen:
                    seen.add(k)
                    out.append(Rule(k, v, (v,), conf, "N102"))

    for col, frm, third in IRREG:
        for i in range(6):
            ce = _PERSON_COL[i] if _PERSON_COL[i] is not None else third
            add(col + ce, frm + _PERSON_FRM[i])
    for stem in REGULAR:
        for i in (2, 4, 5):
            ce = _PERSON_COL[i] if _PERSON_COL[i] is not None else "ه"
            add(stem + ce, stem + _PERSON_FRM[i], "high")
    return out


def _copula_rules() -> List[Rule]:
    out = []
    for s in COPULA_STEMS:
        out.append(Rule(s + "ه", s + " است", (s + " است",), "high", "N103"))
    out.append(Rule("آسونه", "آسان است", ("آسان است",), "high", "N103"))
    out.append(Rule("آسون", "آسان", ("آسان",), "high", "N101"))
    # «ـیه» after a vowel-final adjective («طبیعی» + ه is already  طبیعیه):
    for s in COPULA_STEMS:
        if s.endswith("ی"):
            out.append(Rule(s + "ه", s + " است", (s + " است",), "high", "N103"))
    return out


_CACHE: Optional[List[Rule]] = None


def rules() -> List[Rule]:
    global _CACHE
    if _CACHE is None:
        allr = _parse_table() + _verb_rules() + _copula_rules()
        # one rule per surface: the hand-written table wins over generated entries
        seen, uniq = set(), []
        for r in allr:
            if r.surface in seen:
                continue
            seen.add(r.surface)
            uniq.append(r)
        _CACHE = uniq
    return _CACHE


LETTER = "\u0621-\u063A\u0640-\u0652\u0670-\u06D3\u06D5\u200c"
_LETTER = LETTER
_COMPILED: Optional[Tuple[re.Pattern, Dict[str, Rule]]] = None


def _surface_regex(s: str) -> str:
    # tolerate a space or a half-space where the table has either, and Arabic ي/ك for Persian ی/ک
    out = []
    for ch in s:
        if ch in (" ", ZW):
            out.append(f"[ {ZW}]?" if ch == ZW else f"[ {ZW}]")
        elif ch == "ی":
            out.append("[یي]")
        elif ch == "ک":
            out.append("[کك]")
        else:
            out.append(re.escape(ch))
    return "".join(out)


def normalise_key(s: str) -> str:
    s = s.replace("ي", "ی").replace("ك", "ک").replace("ى", "ی").replace("ۀ", "هٔ").replace(" ", " ")
    return re.sub(f"[ {ZW}]", "", s)


def matcher() -> Tuple[re.Pattern, Dict[str, Rule]]:
    """One alternation of every spoken form, longest first, bounded by non-letters."""
    global _COMPILED
    if _COMPILED is None:
        table: Dict[str, Rule] = {}
        for r in rules():
            table.setdefault(normalise_key(r.surface), r)
        # the key identifies a surface regardless of spaces / half-spaces
        keys = sorted({r.surface for r in rules()}, key=lambda k: -len(k))
        pat = "|".join(_surface_regex(k) for k in keys)
        rx = re.compile(f"(?<![{_LETTER}])(?:{pat})(?![{_LETTER}])")
        _COMPILED = (rx, table)
    return _COMPILED
