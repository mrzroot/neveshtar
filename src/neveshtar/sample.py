def _plain(d: Doc, text: str, kind: str, extra_tab: bool = False) -> None:
    if kind == "h":
        d.heading(text, 1)
    elif kind == "q":
        lead, rest = text.split("|", 1)
        d.p([(lead, B), (rest, "")])
    else:
        d.p(text)


def thesis(path: str, flawed: bool = True) -> str:
    """A small .docx with a bold lead-in run, a quotation, a table of contents-like field and a page-number field."""
    d = Doc()
    items = DRAFT if flawed else CLEAN
    for i, (kind, text) in enumerate(items):
        _plain(d, text, kind)
        if i == 3:
            # a paragraph whose middle is a field result: the tool must leave the field alone and still fix the words around it
            d.p(raw=run_xml("همان‌طور که در شکل ") + field_runs("SEQ Figure \\* ARABIC", "۱") + run_xml(" می‌بینیم، خیلی از دانشجوها دیر می‌خوابن." if flawed else " دیده می‌شود، بسیاری از دانشجویان دیر می‌خوابند."))
    return d.save(path)


def text_lines(flawed: bool = True) -> str:
    items = DRAFT if flawed else CLEAN
    out = []
    for kind, text in items:
        if kind == "h":
            out.append("# " + text)
        else:
            out.append(text.replace("|", ""))
        out.append("")
    return "\n".join(out)


